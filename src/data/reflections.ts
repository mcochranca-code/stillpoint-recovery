/**
 * Returns the same reflection throughout a local calendar day.
 * Local date parts are converted to a day number so time-of-day and time zone
 * offsets do not change the selection during the day.
 */
export function getDailyReflection(date: Date = new Date()): ReflectionContent {
  const localDate = Number.isNaN(date.getTime()) ? new Date() : date;
  const dayNumber = Math.floor(
    Date.UTC(localDate.getFullYear(), localDate.getMonth(), localDate.getDate()) / 86_400_000
  );
  const index = ((dayNumber % reflections.length) + reflections.length) % reflections.length;
  const reflection = reflections[index];

  if (!reflection) {
    throw new Error('The reflections library is empty.');
  }

  return reflection;
}
